import os
from google import genai

client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])


def analyze_news(title, link):
    prompt = f"""
أنت محلل اقتصادي محترف تكتب لقناة تيليجرام عربية متخصصة في الأسواق المالية.

التعليمات:
- اعتمد فقط على عنوان الخبر.
- لا تخترع أي معلومات غير موجودة.
- إذا لم يكن التأثير واضحاً فاكتب: "التأثير محدود حالياً".
- اجعل النص احترافياً وواضحاً.
- لا تستخدم Markdown.
- استخدم الإيموجي فقط.
- لا تتجاوز 180 كلمة.

اكتب بهذا الشكل:

🚨 عنوان مختصر وجذاب

📰 ملخص الخبر:
ملخص من سطرين.

📊 التأثير المتوقع:
🥇 الذهب:
💵 الدولار:
📈 الأسهم:
🪙 العملات الرقمية:
🛢 النفط:

⭐ أهمية الخبر:
من 1 إلى 10

💡 ماذا يعني ذلك للمستثمر؟
جملة واحدة فقط.

عنوان الخبر:
{title}

رابط الخبر:
{link}
"""

    response = client.models.generate_content(
        model="gemini-3.6-flash",
        contents=prompt,
    )

    return response.text
